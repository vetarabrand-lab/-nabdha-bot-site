const {chromium}=require('playwright');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:1000}});
 const errors=[];page.on('pageerror',e=>(errors.push(e.message),console.error('PAGE:',e.message)));
 await page.route('https://permissions.test/**',route=>route.fulfill({contentType:'text/html',body:fs.readFileSync('portal.html','utf8').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'').replace(/<link\b[^>]*>/gi,'')}));
 await page.goto('https://permissions.test/portal.html');
 await page.evaluate(()=>{
   window.PORTAL_LANG='ar';window.PT=x=>x;
   window.db={auth:{onAuthStateChange(){},getSession:()=>new Promise(()=>{})},from(){return {update(payload){window.lastUpdate=payload;return this;},eq(){return this;},select(){return this;},single:async()=>{if(window.failSave)return {error:{message:'test'}};return {data:{id:'staff',permissions:window.lastUpdate.permissions}};}};}};
   window.supabase={createClient:()=>window.db};
 });
 for(const file of ['portal-permissions.js','portal-contacts.js','portal.js'])await page.addScriptTag({path:path.resolve(file)});
 await page.evaluate(()=>{isOwner=true;myClient={id:'client'};staffList=[{id:'staff',full_name:'موظف تجريبي',email:'test@example.invalid',permissions:{analytics:true}}];renderTeam();document.getElementById('addStaffBtn').click();});
 assert.equal(await page.locator('.invite-perm-cb').count(),8);
 assert.equal(await page.locator('.invite-perm-cb:checked').count(),1);
 await page.locator('.invite-perm-cb[data-perm=carts]').check();
 await page.locator('.invite-perm-cb[data-perm=contacts]').check();
 await page.screenshot({path:'../staff-permissions-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.querySelector('#newStaffModal .modal-card').scrollWidth<=document.querySelector('#newStaffModal .modal-card').clientWidth));
 await page.screenshot({path:'../staff-permissions-mobile.png'});
 await page.locator('#newStaffCancelBtn').click();
 await page.evaluate(()=>{document.getElementById('appScreen').style.display='block';document.querySelectorAll('.panel').forEach(p=>p.classList.remove('active'));document.getElementById('staffList').closest('.panel').classList.add('active');});
 await page.locator('.staff-permission-details summary').click();
 await page.locator('.staff-perm-cb[data-perm=carts]').check();
 await page.waitForFunction(()=>document.querySelector('.permission-save-status').textContent.includes('تم حفظ'));
 assert.equal(await page.evaluate(()=>staffList[0].permissions.carts),true);
 assert.equal(await page.evaluate(()=>staffList[0].permissions.analytics),true);
 await page.evaluate(()=>{window.failSave=true;});
 await page.locator('.staff-perm-cb[data-perm=contacts]').click();
 await page.waitForFunction(()=>document.querySelector('.permission-save-status').textContent.includes('تعذّر'));
 assert.equal(await page.locator('.staff-perm-cb[data-perm=contacts]').isChecked(),false);
 await page.evaluate(()=>{isOwner=false;myStaffPermissions={orders:false};document.querySelectorAll('.panel').forEach(p=>p.classList.remove('active'));document.getElementById('panelInbox').classList.add('active');document.querySelector('[data-tab=carts]').click();document.querySelector('[data-tab=orders]').click();document.querySelector('[data-tab=contacts]').click();});
 assert.equal(await page.locator('#panelInbox').evaluate(e=>e.classList.contains('active')),true);
 await page.evaluate(()=>{isOwner=true;window.PORTAL_LANG='en';document.getElementById('addStaffBtn').click();});
 assert.match(await page.locator('#invitePermissions').textContent(),/Abandoned carts/);
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('PASS: eight grouped permissions, legacy defaults, mobile layout, saved permissions, failed-save rollback, direct tab guard, English labels. No real invites sent.');
})().catch(e=>{console.error(e);process.exit(1)});
