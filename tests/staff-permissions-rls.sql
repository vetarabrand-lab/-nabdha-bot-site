begin;
do $$
declare s public.client_staff%rowtype; owner_id uuid; other_id uuid; n integer; event_id uuid:=gen_random_uuid();
begin
 select * into strict s from public.client_staff where user_id is not null limit 1;
 select user_id into owner_id from public.clients where id=s.client_id;
 select id into other_id from public.clients where id<>s.client_id and user_id<>s.user_id limit 1;
 insert into public.store_order_events(id,client_id,store_type,event_type,raw_payload,status) values(event_id,s.client_id,'salla','abandoned_cart','{}','received');
 insert into public.whatsapp_contact_syncs(client_id,source_phone_number_id,synced_at) values(s.client_id,'permission-test',now());
 insert into public.whatsapp_contacts(client_id,source_phone_number_id,phone_number,source_timestamp,received_at) values(s.client_id,'permission-test','966500000001',0,now());
 update public.client_staff set permissions='{}' where id=s.id;
 perform set_config('request.jwt.claim.sub',s.user_id::text,true);
 execute 'set local role authenticated';
 if public.is_platform_admin() then raise exception 'Fixture user must not be admin'; end if;
 if not private.has_staff_permission(s.client_id,'orders') then raise exception 'Legacy orders lost'; end if;
 if private.has_staff_permission(s.client_id,'carts') then raise exception 'Missing cart grant'; end if;
 if private.has_staff_permission(other_id,'orders') then raise exception 'Cross tenant access'; end if;
 select count(*) into n from public.store_order_events where id=event_id;
 if n<>0 then raise exception 'Cart RLS leaked'; end if;
 select count(*) into n from public.whatsapp_contacts where source_phone_number_id='permission-test';
 if n<>0 then raise exception 'Contacts RLS leaked'; end if;
 if public.my_cart_reminder_policy(s.client_id) is not null then raise exception 'Cart RPC leaked'; end if;
 execute 'reset role';
 update public.client_staff set permissions='{"carts":true,"contacts":true,"orders":false}' where id=s.id;
 execute 'set local role authenticated';
 if private.has_staff_permission(s.client_id,'orders') then raise exception 'Explicit order denial ignored'; end if;
 select count(*) into n from public.store_order_events where id=event_id;
 if n<>1 then raise exception 'Granted carts inaccessible'; end if;
 select count(*) into n from public.whatsapp_contacts where source_phone_number_id='permission-test';
 if n<>1 then raise exception 'Granted contacts inaccessible'; end if;
 if public.my_cart_reminder_policy(s.client_id) is null then raise exception 'Granted RPC inaccessible'; end if;
 update public.client_staff set permissions='{"orders":true}' where id=s.id;
 get diagnostics n = row_count;
 if n<>0 then raise exception 'Staff self escalation'; end if;
 begin
   perform public.sync_whatsapp_contacts(s.client_id);
   raise exception 'Staff sync must fail';
 exception when insufficient_privilege then null;
 end;
 execute 'reset role';
 update public.client_staff set permissions='{"carts":"true","contacts":false}' where id=s.id;
 execute 'set local role authenticated';
 if private.has_staff_permission(s.client_id,'carts') then raise exception 'String true accepted'; end if;
 select count(*) into n from public.whatsapp_contacts where source_phone_number_id='permission-test';
 if n<>0 then raise exception 'Revoked contacts accessible'; end if;
 execute 'reset role';
 perform set_config('request.jwt.claim.sub',owner_id::text,true);
 execute 'set local role authenticated';
 if not private.has_staff_permission(s.client_id,'carts') then raise exception 'Owner denied'; end if;
 select count(*) into n from public.store_order_events where id=event_id;
 if n<>1 then raise exception 'Owner cart inaccessible'; end if;
 execute 'reset role';
end $$;
